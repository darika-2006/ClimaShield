export const LanguageProvider = ({ children }) => {
  const [language, setLanguage] = useState(() => localStorage.getItem('climashield_lang') || 'en');

  useEffect(() => {
    localStorage.setItem('climashield_lang', language);
  }, [language]);

  const t = (key) => {
    return translations[language]?.[key] || translations['en']?.[key] || key;
  };

  const tDistrict = (name) => {
    if (!name || typeof name !== 'string') return name;
    if (language !== 'ta') return name;
    if (districtTranslations[name]) return districtTranslations[name];
    let result = name;
    for (const [enKey, taVal] of Object.entries(districtTranslations)) {
      if (result.includes(enKey)) {
        result = result.replace(new RegExp(enKey, 'g'), taVal);
      }
    }
    return result;
  };

  const tHazard = (hazardStr) => {
    if (!hazardStr || typeof hazardStr !== 'string') return hazardStr;
    if (language !== 'ta') return hazardStr;
    if (hazardTranslations[hazardStr]) return hazardTranslations[hazardStr];
    let result = hazardStr;
    for (const [enKey, taVal] of Object.entries(hazardTranslations)) {
      if (result.includes(enKey)) {
        result = result.replace(new RegExp(enKey, 'g'), taVal);
      }
    }
    return result;
  };

  const tZone = (zoneStr) => {
    if (!zoneStr || typeof zoneStr !== 'string') return zoneStr;
    if (language !== 'ta') return zoneStr;
    if (zoneTranslations[zoneStr]) return zoneTranslations[zoneStr];
    let result = zoneStr;
    for (const [enKey, taVal] of Object.entries(zoneTranslations)) {
      if (result.includes(enKey)) {
        result = result.replace(new RegExp(enKey, 'g'), taVal);
      }
    }
    return result;
  };

  const toggleLanguage = () => {
    setLanguage((prev) => (prev === 'en' ? 'ta' : 'en'));
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t, tDistrict, tHazard, tZone, toggleLanguage }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => useContext(LanguageContext);
